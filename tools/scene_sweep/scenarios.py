#!/usr/bin/env python3
"""Test scenarios: named game states made from a known start save by a small script of the game's language.

Test tooling only (scenarios/README.md). Each scenarios/<name>.c sets up its state with the game's own functions when
the start save loads (through the game's migration hook), then saves the game as "scenario-<name>": later runs load
that save directly. The saves hold game data: keep them out of the repository (a local, ignored folder).

  scenarios.py list
  scenarios.py device NAME -s SERIAL [--start SAVE] [--package P] [--saves DIR] [--timeout S]
        injects the scenario into the game on a device (an emulator started with -read-only: the files go away with
        its overlay), waits until the start save is loaded there (title -> load, by hand or ui_crawl.py) and the
        scenario saved, pulls the save into DIR (default: none) and removes the injected files
  scenarios.py device-clear -s SERIAL [--package P]
  scenarios.py sweep NAME... --game DIR --engine FILE --save FILE --out DIR [--saves DIR] [run.py options]
        the scene sweep's scenario:<name> scene, one engine run per scenario (run.py --scenario), on the host
"""
import argparse
import re
import shutil
import subprocess
import sys
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent
SCENARIOS = HERE / 'scenarios'
DRIVER = 'scenario.c'
HEADER = re.compile(r'^// Scenario (?P<name>[a-z0-9_]+): (?P<text>.+)$', re.M)
DEVICE_PACKAGE = 'org.stormengine.port.game'


def scenarios():
    """{name: one-line description} of every scenarios/<name>.c (its "// Scenario <name>: ..." line)."""
    found = {}
    for path in sorted(SCENARIOS.glob('*.c')):
        if path.name == DRIVER:
            continue
        match = HEADER.search(path.read_text(encoding='utf-8'))
        if not match or match.group('name') != path.stem:
            sys.exit(f'{path}: needs a "// Scenario {path.stem}: <what it sets up>" line')
        found[path.stem] = match.group('text')
    return found


def check_name(name):
    known = scenarios()
    if name not in known:
        sys.exit(f'no scenario {name!r}; known: {", ".join(known)}')


def migration_name(existing, name):
    """The game numbers its migrations 0001.. without gaps (migrations.c sizes its list by the file count)."""
    numbers = sorted(int(item[:4]) for item in existing if re.fullmatch(r'\d{4}_.+\.c', item, re.I))
    if numbers != list(range(1, len(numbers) + 1)):
        sys.exit(f'the game\'s migrations are not numbered 0001..{len(numbers):04d}: {numbers}')
    return f'{len(numbers) + 1:04d}_scenario_{name}.c'


def migration_text(name):
    return (f'// Generated by tools/scene_sweep/scenarios.py: runs the test scenario {name} while the save loads.\n'
            f'// Test tooling only, never part of the game.\n'
            f'extern void Scenario_Run(string name);\n\n'
            f'void ApplyMigration(ref migrationState)\n{{\n'
            f'\tif (!LoadSegment("scenarios/{name}.c"))\n\t{{\n'
            f'\t\ttrace("Scenario {name}: FAILED the segment scenarios/{name}.c did not load (error.log)");\n'
            f'\t\treturn;\n\t}}\n'
            f'\tScenario_Run("{name}");\n}}\n')


def install(name, existing):
    """Files a game copy gets for scenario `name`: {relative path under PROGRAM: text}."""
    files = {f'scenarios/{DRIVER}': (SCENARIOS / DRIVER).read_text(encoding='utf-8'),
             f'scenarios/{name}.c': (SCENARIOS / f'{name}.c').read_text(encoding='utf-8'),
             f'migrations/{migration_name(existing, name)}': migration_text(name)}
    return files


# ---------------------------------------------------------------- device

class Device:
    def __init__(self, serial, package):
        self.serial, self.package = serial, package
        self.game = f'/sdcard/Android/data/{package}/files/game'

    def adb(self, *args, check=True, binary=False):
        out = subprocess.run(['adb', '-s', self.serial, *args], capture_output=True)
        if check and out.returncode:
            sys.exit(f'adb {" ".join(args)}: {out.stderr.decode(errors="replace").strip()}')
        return out.stdout if binary else out.stdout.decode('utf-8', 'replace')

    def shell(self, command, check=True):
        return self.adb('shell', command, check=check)

    def program(self):
        listing = self.shell(f'ls {self.game}/', check=False).split()
        program = next((item for item in listing if item.lower() == 'program'), None)
        if not program:
            sys.exit(f'{self.serial}: no game in {self.game}')
        return f'{self.game}/{program}'

    def read_only(self):
        """An emulator started with -read-only (its changes go away with the overlay); refuse other devices."""
        if not self.serial.startswith('emulator-'):
            return False
        avd = self.adb('emu', 'avd', 'name', check=False)
        cmdline = subprocess.run(['pgrep', '-af', '--', f'-port {self.serial.split("-", 1)[1]}'], capture_output=True,
                                 text=True).stdout
        return '-read-only' in cmdline or 'read-only' in avd

    def clear(self):
        program = self.program()
        self.shell(f'rm -rf {program}/scenarios; rm -f {program}/migrations/*_scenario_*.c', check=False)


def device_run(arguments):
    check_name(arguments.name)
    device = Device(arguments.serial, arguments.package)
    if not device.read_only() and not arguments.any_device:
        sys.exit(f'{arguments.serial} is not an emulator started with -read-only: the scenario changes the game files '
                 f'there (--any-device to allow it)')
    program = device.program()
    device.clear()
    existing = device.shell(f'ls {program}/migrations/', check=False).split()
    files = install(arguments.name, existing)
    staging = Path(subprocess.run(['mktemp', '-d'], capture_output=True, text=True, check=True).stdout.strip())
    try:
        for relative, text in files.items():
            local = staging / relative
            local.parent.mkdir(parents=True, exist_ok=True)
            # The game's scripts are Windows-1251; ours are ASCII apart from comments, which the compiler skips.
            local.write_bytes(text.encode('cp1251', errors='replace'))
            folder = f'{program}/{Path(relative).parent}'
            # A folder adb makes there is the shell user's: the app may enter it only when everyone may.
            device.shell(f'[ -d {folder} ] || {{ mkdir -p {folder} && chmod 777 {folder}; }}')
            device.adb('push', str(local), f'{program}/{relative}')
    finally:
        shutil.rmtree(staging)
    if arguments.start:
        # Earlier scenario records go (they are pulled already): the start save must be the newest record, the one
        # the title's «Продолжить» loads. Then the start save as "scenario-start" of the player's profile.
        device.shell(f"run-as {arguments.package} sh -c 'for f in files/storm/SaveData/*/scenario-*; do "
                     f"case $f in */scenario-start) ;; *) rm -f \"$f\" ;; esac; done'", check=False)
        device.adb('push', str(arguments.start), '/data/local/tmp/scenario-start')
        device.shell('chmod 644 /data/local/tmp/scenario-start')
        device.shell(f'run-as {arguments.package} cp /data/local/tmp/scenario-start files/storm/SaveData/player/scenario-start'
                     f' && rm /data/local/tmp/scenario-start')
    print(f'injected scenario {arguments.name}: ' + ', '.join(files), flush=True)
    print('now load the start save on the device (title -> load); waiting for the scenario ...', flush=True)
    device.adb('logcat', '-c', check=False)
    start, result = time.time(), None
    while time.time() - start < arguments.timeout:
        log = device.adb('logcat', '-d', '-s', 'StormEngine:*', 'Storm:*', 'storm:*', '*:I', check=False)
        lines = [line for line in log.splitlines() if f'Scenario {arguments.name}:' in line]
        if any('FAILED' in line for line in lines):
            result = 'failed'
        elif any(line.rstrip().endswith(': done') for line in lines):
            result = 'done'
        if result:
            break
        time.sleep(2)
    for line in lines if result else []:
        print('  ' + line.split(f'Scenario {arguments.name}:', 1)[1].strip())
    if result != 'done':
        device.clear()
        sys.exit(f'scenario {arguments.name}: {result or "no result within %d s" % arguments.timeout}')
    if arguments.saves:
        # "saved SAVE\<profile>\<record> in <location>": the start save's profile (files/storm/SaveData/<profile>).
        saved = next((re.search(r'saved SAVE\\(.+?)\\(\S+) in ', line) for line in lines if ': saved SAVE' in line), None)
        if not saved:
            sys.exit('the scenario did not say where it saved')
        profile, record = saved.groups()
        pulled = subprocess.run(['adb', '-s', arguments.serial, 'exec-out', 'run-as', arguments.package, 'cat',
                                 f'files/storm/SaveData/{profile}/{record}'], capture_output=True)
        if pulled.returncode or len(pulled.stdout) < 4096:
            sys.exit(f'cannot read the save {profile}/{record} on the device: {pulled.stdout[:200]!r}')
        arguments.saves.mkdir(parents=True, exist_ok=True)
        (arguments.saves / record).write_bytes(pulled.stdout)
        print(f'save: {arguments.saves / record} ({len(pulled.stdout)} bytes)')
    if not arguments.keep:
        device.clear()


def device_clear(arguments):
    Device(arguments.serial, arguments.package).clear()


# ---------------------------------------------------------------- host scene sweep

def sweep(arguments, rest):
    for name in arguments.names:
        check_name(name)
    failed = []
    for name in arguments.names:
        out = arguments.out / name
        command = [sys.executable, str(HERE / 'run.py'), '--game', str(arguments.game), '--engine', str(arguments.engine),
                   '--save', str(arguments.save), '--out', str(out), '--scenario', name, '--jobs', '1',
                   '--single-session', *rest]
        print('$ ' + ' '.join(command), flush=True)
        if subprocess.run(command).returncode:
            failed.append(name)
            continue
        record = out / 'saves' / f'scenario-{name}'
        if arguments.saves and record.is_file():
            arguments.saves.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(record, arguments.saves / record.name)
            print(f'save: {arguments.saves / record.name}')
    if failed:
        sys.exit('failed: ' + ' '.join(failed))


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    commands = parser.add_subparsers(dest='command', required=True)
    commands.add_parser('list')
    run = commands.add_parser('device')
    run.add_argument('name')
    run.add_argument('-s', '--serial', required=True)
    run.add_argument('--package', default=DEVICE_PACKAGE)
    run.add_argument('--saves', type=Path, help='folder for the scenario save pulled from the device')
    run.add_argument('--start', type=Path, help='put this start save on the device as the record "scenario-start"')
    run.add_argument('--timeout', type=int, default=900, help='seconds to wait for the scenario (default 900)')
    run.add_argument('--keep', action='store_true', help='leave the injected files on the device')
    run.add_argument('--any-device', action='store_true', help='allow a device that is not a read-only emulator')
    clear = commands.add_parser('device-clear')
    clear.add_argument('-s', '--serial', required=True)
    clear.add_argument('--package', default=DEVICE_PACKAGE)
    host = commands.add_parser('sweep')
    host.add_argument('names', nargs='+')
    host.add_argument('--game', type=Path, required=True)
    host.add_argument('--engine', type=Path, required=True)
    host.add_argument('--save', type=Path, required=True, help='the start save (a save made on land)')
    host.add_argument('--out', type=Path, required=True)
    host.add_argument('--saves', type=Path, help='folder the scenario saves are copied to')
    arguments, rest = parser.parse_known_args()
    if arguments.command != 'sweep' and rest:
        parser.error('unrecognized arguments: ' + ' '.join(rest))
    if arguments.command == 'list':
        for name, text in scenarios().items():
            print(f'{name:<16} {text}')
    elif arguments.command == 'device':
        device_run(arguments)
    elif arguments.command == 'device-clear':
        device_clear(arguments)
    else:
        sweep(arguments, rest)


if __name__ == '__main__':
    main()
