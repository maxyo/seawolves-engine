#!/usr/bin/env python3
"""Embeds compiled shader blobs into the program (storm_shaders.cmake, fx/cmake/storm_fx_shaders.cmake):

  shader_blobs.py <namespace> <directory> <name>...

For every <name>, <directory>/<name>.bin (OpenGL ES) and <directory>/<name>.spv.bin (Vulkan) are shaderc's binary
output. Writes, each only when its content changes:
- <directory>/blobs.cpp: the blobs as data, through the assembler's .incbin, which copies the bytes. A C array of
  ~120 MB of shaders (shaderc --bin2c) took the compiler 100 CPU-seconds and 3-4 minutes of build on every shader
  change, and carried the data through the LTO bitcode. The file names each blob's SHA-256, so a changed blob
  changes the source (and the ccache key: ccache does not read .incbin files). Compiled without LTO (cmake).
- <directory>/includes.inc: for each blob a `static const uint8_t (&<name>)[size]` reference to its symbol (and
  <name>_spv), so code that included the old headers is unchanged: storm/render/shader_blob.hpp
  (STORM_SHADER_BLOB) takes the arrays and their sizeof.
"""
import hashlib
from pathlib import Path
import sys


def write_if_changed(path, text):
    if not path.exists() or path.read_text() != text:
        path.write_text(text)


def main():
    namespace, directory, *names = sys.argv[1:]
    directory = Path(directory).resolve()
    declarations = [f'// Generated by renderer_bgfx/cmake/shader_blobs.py: the shader blobs of {namespace} (blobs.cpp).',
                    '#include <cstdint>']
    assembly = []
    for name in names:
        for array, suffix in ((name, '.bin'), (f'{name}_spv', '.spv.bin')):
            blob = directory / f'{name}{suffix}'
            data = blob.read_bytes()
            if not data:
                sys.exit(f'shader_blobs.py: {blob} is empty')
            symbol = f'{namespace}__{array}'
            declarations.append(f'extern "C" __attribute__((visibility("hidden"))) const uint8_t {symbol}[{len(data)}];')
            declarations.append(f'[[maybe_unused]] static const uint8_t (&{array})[{len(data)}] = {symbol};')
            path = str(blob).replace('\\', '\\\\').replace('"', '\\"')
            assembly.append(f'// {array}: {len(data)} bytes, sha256 {hashlib.sha256(data).hexdigest()}')
            for line in (f'.globl {symbol}', f'.hidden {symbol}', f'.type {symbol}, %object', f'{symbol}:',
                         f'.incbin \\"{path}\\"', f'.size {symbol}, .-{symbol}', '.balign 16'):
                assembly.append(f'"{line}\\n"')
    source = [f'// Generated by renderer_bgfx/cmake/shader_blobs.py: the shader blobs of {namespace}, see includes.inc.',
              '__asm__(', f'".pushsection .rodata.{namespace}, \\"a\\"\\n"', '".balign 16\\n"', *assembly,
              '".popsection\\n");', '']
    write_if_changed(directory / 'blobs.cpp', '\n'.join(source))
    write_if_changed(directory / 'includes.inc', '\n'.join(declarations) + '\n')


if __name__ == '__main__':
    main()
